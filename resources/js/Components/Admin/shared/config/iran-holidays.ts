/**
 * تعطیلات رسمی ایران (اعلامی / مصوب).
 * مناسبت‌های قمری ممکن است با اعلام هلال یک روز جابه‌جا شوند.
 */

export type IranHolidayKind = "national" | "religious";

export type IranHoliday = {
  /** کلید یکتا: YYYY-MM-DD جلالی */
  key: string;
  year: number;
  month: number;
  day: number;
  title: string;
  kind: IranHolidayKind;
};

function h(
  year: number,
  month: number,
  day: number,
  title: string,
  kind: IranHolidayKind = "national",
): IranHoliday {
  return {
    key: `${year}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`,
    year,
    month,
    day,
    title,
    kind,
  };
}

